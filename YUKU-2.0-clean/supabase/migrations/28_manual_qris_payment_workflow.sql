-- Customer submits proof; this never marks the payment settled.
CREATE OR REPLACE FUNCTION public.submit_qris_payment_proof(
  p_booking_id UUID,
  p_proof_storage_path TEXT,
  p_claimed_amount BIGINT,
  p_transfer_reference TEXT DEFAULT NULL
) RETURNS UUID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_booking public.bookings%ROWTYPE;
  v_settings public.qris_payment_settings%ROWTYPE;
  v_submission_id UUID;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required.'; END IF;
  IF p_claimed_amount IS NULL OR p_claimed_amount <= 0 THEN RAISE EXCEPTION 'Nominal pembayaran tidak valid.'; END IF;
  IF p_proof_storage_path IS NULL OR p_proof_storage_path !~ ('^' || p_booking_id::text || '/[A-Za-z0-9._-]+$') THEN
    RAISE EXCEPTION 'Lokasi bukti pembayaran tidak valid.';
  END IF;
  SELECT * INTO v_booking FROM public.bookings WHERE id = p_booking_id FOR UPDATE;
  IF NOT FOUND OR v_booking.customer_id <> auth.uid() THEN RAISE EXCEPTION 'Booking tidak ditemukan.'; END IF;
  IF v_booking.status <> 'pending_payment' THEN RAISE EXCEPTION 'Booking tidak lagi menunggu pembayaran.'; END IF;
  IF v_booking.payment_expires_at <= NOW() THEN RAISE EXCEPTION 'Batas waktu pembayaran telah kedaluwarsa.'; END IF;
  IF p_claimed_amount <> v_booking.gross_amount THEN RAISE EXCEPTION 'Nominal harus sama persis dengan total booking.'; END IF;

  -- Atomically lock this booking to the manual QRIS route before accepting proof.
  -- If Xendit has already claimed the booking, QRIS is rejected.
  PERFORM public.claim_booking_payment_route(p_booking_id, 'manual_qris');
  SELECT * INTO v_settings FROM public.qris_payment_settings WHERE id = TRUE;
  IF NOT FOUND OR NOT v_settings.is_active THEN RAISE EXCEPTION 'Pembayaran QRIS sedang tidak aktif.'; END IF;
  IF EXISTS (SELECT 1 FROM public.qris_payment_submissions WHERE booking_id = p_booking_id AND status = 'pending_review') THEN
    RAISE EXCEPTION 'Bukti pembayaran untuk booking ini masih menunggu pemeriksaan Admin.';
  END IF;
  INSERT INTO public.qris_payment_submissions(booking_id, customer_id, proof_storage_path, claimed_amount, transfer_reference)
  VALUES (p_booking_id, auth.uid(), p_proof_storage_path, p_claimed_amount, NULLIF(trim(COALESCE(p_transfer_reference,'')),''))
  RETURNING id INTO v_submission_id;
  -- Manual review needs more than the original 15-minute reservation window.
  -- Keep the slot reserved for up to 24 hours after proof submission.
  UPDATE public.bookings SET payment_expires_at = GREATEST(payment_expires_at, NOW() + INTERVAL '24 hours'), updated_at = NOW()
  WHERE id = p_booking_id;
  RETURN v_submission_id;
END; $$;
REVOKE ALL ON FUNCTION public.submit_qris_payment_proof(UUID, TEXT, BIGINT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_qris_payment_proof(UUID, TEXT, BIGINT, TEXT) TO authenticated;

-- Admin changes the active QRIS asset. Paths are immutable/versioned by caller.
CREATE OR REPLACE FUNCTION public.admin_update_qris_settings(
  p_is_active BOOLEAN,
  p_image_path TEXT,
  p_merchant_name TEXT DEFAULT NULL,
  p_merchant_identifier TEXT DEFAULT NULL,
  p_instructions TEXT DEFAULT NULL
) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_old JSONB; v_new JSONB;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN RAISE EXCEPTION 'Akses ditolak: Admin saja.'; END IF;
  IF p_is_active AND NULLIF(trim(COALESCE(p_image_path,'')), '') IS NULL THEN RAISE EXCEPTION 'Gambar QRIS wajib tersedia sebelum diaktifkan.'; END IF;
  SELECT to_jsonb(s) INTO v_old FROM public.qris_payment_settings s WHERE id = TRUE;
  INSERT INTO public.qris_payment_settings(id,is_active,image_path,merchant_name,merchant_identifier,instructions,updated_by,updated_at)
  VALUES(TRUE,COALESCE(p_is_active,FALSE),NULLIF(trim(COALESCE(p_image_path,'')),''),NULLIF(trim(COALESCE(p_merchant_name,'')),''),NULLIF(trim(COALESCE(p_merchant_identifier,'')),''),COALESCE(NULLIF(trim(COALESCE(p_instructions,'')),''),'Scan QRIS, bayar sesuai nominal, lalu unggah bukti pembayaran.'),auth.uid(),NOW())
  ON CONFLICT(id) DO UPDATE SET is_active=EXCLUDED.is_active,image_path=EXCLUDED.image_path,merchant_name=EXCLUDED.merchant_name,merchant_identifier=EXCLUDED.merchant_identifier,instructions=EXCLUDED.instructions,updated_by=EXCLUDED.updated_by,updated_at=NOW();
  SELECT to_jsonb(s) INTO v_new FROM public.qris_payment_settings s WHERE id = TRUE;
  INSERT INTO public.qris_payment_audit_logs(actor_user_id,action,old_values,new_values)
  VALUES(auth.uid(),'settings_changed',v_old,v_new);
  RETURN TRUE;
END; $$;
REVOKE ALL ON FUNCTION public.admin_update_qris_settings(BOOLEAN,TEXT,TEXT,TEXT,TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_update_qris_settings(BOOLEAN,TEXT,TEXT,TEXT,TEXT) TO authenticated;

-- Admin verifies the actual credit in the merchant/bank app before approval.
-- The payment row is first inserted pending, then updated to settled_held so the
-- existing AFTER UPDATE ledger trigger creates commission/earnings/referral rows.
CREATE OR REPLACE FUNCTION public.admin_review_qris_payment(
  p_submission_id UUID,
  p_approve BOOLEAN,
  p_admin_notes TEXT,
  p_transfer_reference TEXT DEFAULT NULL
) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_submission public.qris_payment_submissions%ROWTYPE;
  v_booking public.bookings%ROWTYPE;
  v_payment public.payments%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN RAISE EXCEPTION 'Akses ditolak: Admin saja.'; END IF;
  IF NULLIF(trim(COALESCE(p_admin_notes,'')), '') IS NULL THEN RAISE EXCEPTION 'Catatan pemeriksaan wajib diisi.'; END IF;
  SELECT * INTO v_submission FROM public.qris_payment_submissions WHERE id=p_submission_id FOR UPDATE;
  IF NOT FOUND OR v_submission.status <> 'pending_review' THEN RAISE EXCEPTION 'Pengajuan tidak ditemukan atau sudah diproses.'; END IF;
  SELECT * INTO v_booking FROM public.bookings WHERE id=v_submission.booking_id FOR UPDATE;
  IF NOT FOUND OR v_booking.status <> 'pending_payment' THEN RAISE EXCEPTION 'Booking tidak lagi menunggu pembayaran.'; END IF;
  IF v_booking.payment_expires_at <= NOW() THEN RAISE EXCEPTION 'Booking telah kedaluwarsa; pembayaran tidak boleh disahkan otomatis.'; END IF;
  IF v_booking.payment_route IS DISTINCT FROM 'manual_qris' THEN
    RAISE EXCEPTION 'Booking ini tidak terkunci pada jalur QRIS.';
  END IF;
  IF p_approve THEN
    IF p_transfer_reference IS NULL OR trim(p_transfer_reference) = '' THEN RAISE EXCEPTION 'Referensi transaksi bank/merchant wajib dicatat.'; END IF;
    SELECT * INTO v_payment FROM public.payments WHERE booking_id=v_booking.id FOR UPDATE;
    IF NOT FOUND THEN
      INSERT INTO public.payments(booking_id,provider,provider_charge_id,payment_method,amount,payment_status,paid_at)
      VALUES(v_booking.id,'manual_qris',left(trim(p_transfer_reference),100),'qris',v_booking.gross_amount,'pending',NULL)
      RETURNING * INTO v_payment;
    END IF;
    IF v_payment.payment_status NOT IN ('pending','failed') THEN RAISE EXCEPTION 'Status pembayaran tidak dapat disahkan.'; END IF;
    UPDATE public.payments SET provider='manual_qris',provider_charge_id=left(trim(p_transfer_reference),100),payment_method='qris',amount=v_booking.gross_amount,payment_status='settled_held',paid_at=NOW(),updated_at=NOW() WHERE id=v_payment.id;
    UPDATE public.bookings SET status='paid_held_in_escrow',updated_at=NOW() WHERE id=v_booking.id;
    UPDATE public.qris_payment_submissions SET status='approved',admin_user_id=auth.uid(),admin_notes=trim(p_admin_notes),reviewed_at=NOW() WHERE id=p_submission_id;
    INSERT INTO public.qris_payment_audit_logs(actor_user_id,action,booking_id,submission_id,new_values,reason)
    VALUES(auth.uid(),'payment_approved',v_booking.id,p_submission_id,jsonb_build_object('amount',v_booking.gross_amount,'transfer_reference',trim(p_transfer_reference)),trim(p_admin_notes));
  ELSE
    UPDATE public.qris_payment_submissions SET status='rejected',admin_user_id=auth.uid(),admin_notes=trim(p_admin_notes),reviewed_at=NOW() WHERE id=p_submission_id;
    INSERT INTO public.qris_payment_audit_logs(actor_user_id,action,booking_id,submission_id,reason)
    VALUES(auth.uid(),'payment_rejected',v_booking.id,p_submission_id,trim(p_admin_notes));
  END IF;
  RETURN TRUE;
END; $$;
REVOKE ALL ON FUNCTION public.admin_review_qris_payment(UUID,BOOLEAN,TEXT,TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_review_qris_payment(UUID,BOOLEAN,TEXT,TEXT) TO authenticated;

