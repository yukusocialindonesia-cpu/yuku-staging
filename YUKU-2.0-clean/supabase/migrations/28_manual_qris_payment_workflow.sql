-- Current QRIS configuration. The image path is versioned and never overwritten.
CREATE TABLE IF NOT EXISTS public.qris_payment_settings (
  id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id = TRUE),
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  image_path TEXT,
  merchant_name TEXT,
  merchant_identifier TEXT,
  instructions TEXT NOT NULL DEFAULT 'Scan QRIS, bayar sesuai nominal, lalu unggah bukti pembayaran.',
  updated_by UUID REFERENCES public.users(id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (NOT is_active OR image_path IS NOT NULL)
);
INSERT INTO public.qris_payment_settings (id, is_active)
VALUES (TRUE, FALSE) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.qris_payment_submissions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id UUID NOT NULL REFERENCES public.bookings(id),
  customer_id UUID NOT NULL REFERENCES public.users(id),
  proof_storage_path TEXT NOT NULL,
  claimed_amount BIGINT NOT NULL CHECK (claimed_amount > 0),
  transfer_reference TEXT,
  status TEXT NOT NULL DEFAULT 'pending_review'
    CHECK (status IN ('pending_review', 'approved', 'rejected')),
  admin_user_id UUID REFERENCES public.users(id),
  admin_notes TEXT,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((status = 'pending_review' AND admin_user_id IS NULL AND reviewed_at IS NULL)
      OR (status <> 'pending_review' AND admin_user_id IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_qris_submissions_status_created
  ON public.qris_payment_submissions(status, created_at DESC);
-- A rejected proof may be replaced, but only one submission may await review per booking.
CREATE UNIQUE INDEX IF NOT EXISTS uq_qris_one_pending_submission_per_booking
  ON public.qris_payment_submissions(booking_id) WHERE status = 'pending_review';

CREATE TABLE IF NOT EXISTS public.qris_payment_audit_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_user_id UUID NOT NULL REFERENCES public.users(id),
  action TEXT NOT NULL CHECK (action IN ('settings_changed', 'payment_approved', 'payment_rejected')),
  booking_id UUID REFERENCES public.bookings(id),
  submission_id UUID REFERENCES public.qris_payment_submissions(id),
  old_values JSONB,
  new_values JSONB,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_qris_audit_created ON public.qris_payment_audit_logs(created_at DESC);

